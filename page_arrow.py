"""
HUD compass arrow that points at the next Bible page (or the exit once it is open).

Uses the golden arrow art from assets/sprites/bible_page_arrow_f0..f3.png (pulsing glow,
generated by tools/make_bible_arrow.py). The art is pre-centred on the arrow's own middle
so it spins like a compass needle, then rotated to the target's bearing relative to where
the player is facing: up = straight ahead, right = target on the player's right.

If the sprites are missing the arrow falls back to a plain drawn triangle.
"""
import math
import os

import pygame

try:
    from settings import BASE_PATH
except Exception:                                   # pragma: no cover - standalone use
    BASE_PATH = os.path.dirname(os.path.abspath(__file__))

SPRITE_DIR = os.path.join(BASE_PATH, 'assets', 'sprites')
BASE_FILE = 'bible_page_arrow_base.png'             # crisp arrow, used to find its centre
FRAME_FILES = tuple(f'bible_page_arrow_f{i}.png' for i in range(4))

# Which way the arrow reads as pointing in the source art. The shaft is a curve (see
# tools/make_bible_arrow.py): the tail is at P0 = (204, 84) and the tip at (50, 426) in image
# space (y down). The tail->tip line is what the eye follows, not the head's own axis, which
# is ~27 degrees more to the left. Clockwise-from-up bearing in degrees: atan2(dx, -dy).
ART_BEARING_DEG = math.degrees(math.atan2(50.0 - 204.0, -(426.0 - 84.0)))


def rotation_for(rel, art_bearing_deg=ART_BEARING_DEG):
    """Counter-clockwise degrees to rotate the art so it points `rel` radians clockwise of up."""
    return art_bearing_deg - math.degrees(rel)


class PageArrow:
    STEP_DEG = 6          # rotation cache granularity
    FRAME_MS = 140        # glow animation speed

    def __init__(self, size=36):
        self.size = size
        self._art_bearing = ART_BEARING_DEG
        self._cache = {}
        self._frames = self._load_frames(size)
        if not self._frames:
            self._frames = [self._fallback(size)]
            self._art_bearing = 0.0                 # fallback is drawn pointing straight up

    # ── loading ───────────────────────────────────────────────────────────
    @staticmethod
    def _load(name):
        img = pygame.image.load(os.path.join(SPRITE_DIR, name))
        return img.convert_alpha() if pygame.display.get_surface() else img

    def _load_frames(self, size):
        try:
            base = self._load(BASE_FILE)
            box = base.get_bounding_rect()
            cx, cy = box.center
            half = max(box.w, box.h) // 2 + 24      # + margin for the baked-in glow
            frames = []
            for name in FRAME_FILES:
                img = self._load(name)
                canvas = pygame.Surface((half * 2, half * 2), pygame.SRCALPHA)
                canvas.blit(img, (half - cx, half - cy))   # arrow centre -> canvas centre
                frames.append(pygame.transform.smoothscale(canvas, (size, size)))
            return frames
        except (pygame.error, OSError):
            return []

    @staticmethod
    def _fallback(size):
        surf = pygame.Surface((size, size), pygame.SRCALPHA)
        s = size
        pts = [(s * 0.5, s * 0.06), (s * 0.88, s * 0.82), (s * 0.5, s * 0.62), (s * 0.12, s * 0.82)]
        pygame.draw.polygon(surf, (255, 215, 0), pts)
        pygame.draw.polygon(surf, (96, 64, 12), pts, 2)
        return surf

    # ── drawing ───────────────────────────────────────────────────────────
    def get(self, rel, t_ms):
        """Rotated arrow surface for a target `rel` radians clockwise of straight ahead."""
        frame = int(t_ms // self.FRAME_MS) % len(self._frames)
        steps = 360 // self.STEP_DEG
        step = int(round(rotation_for(rel, self._art_bearing) / self.STEP_DEG)) % steps
        key = (frame, step)
        img = self._cache.get(key)
        if img is None:
            img = pygame.transform.rotozoom(self._frames[frame], step * self.STEP_DEG, 1.0)
            self._cache[key] = img
        return img

    def draw(self, surf, cx, cy, rel, t_ms):
        img = self.get(rel, t_ms)
        surf.blit(img, (cx - img.get_width() // 2, cy - img.get_height() // 2))
